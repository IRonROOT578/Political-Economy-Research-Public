def hilbert(x, y, n=1 << 10):
    d, t = 0, n >> 1
    while t:
        rx, ry = int(x & t > 0), int(y & t > 0)
        d += t * t * ((3 * rx) ^ ry)
        if ry == 0:
            if rx == 1:
                x, y = n - 1 - x, n - 1 - y
            x, y = y, x
        t >>= 1
    return d


def load_units(year):
    """資料/legis-YYYY.csv：市鎮×選區（2024 由逐投票所加總）。回傳 [(省, 排序鍵, 選舉人, 依 國左中共右極他 的票)]；
    排序鍵＝省內依市鎮座標的 Hilbert 位置（同座標再依選區、市鎮碼）。"""
    with open(os.path.join(HERE, "資料", f"legis-{year}.csv"), encoding="utf-8") as f:
        rows = list(csv.reader(f))[1:]
    by = {}
    for r in rows:
        by.setdefault(r[0], []).append(r)
    out = []
    for dep, rs in by.items():
        xs = [float(r[3]) * 0.7 for r in rs]
        ys = [float(r[4]) for r in rs]
        x0, y0 = min(xs), min(ys)
        span = max(max(xs) - x0, max(ys) - y0) or 1.0
        for r, x, y in zip(rs, xs, ys):
            key = (hilbert(int((x - x0) / span * 1023), int((y - y0) / span * 1023)), int(r[1]) if r[1].isdigit() else 0, r[2])
            out.append((dep, key, int(r[5]), tuple(int(v) for v in r[6:13])))
    return out



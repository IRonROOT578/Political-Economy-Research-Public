def shares(target, bias, name):
    b = bias.get(name, {})
    raw = {p: target[p] * b.get(p, 1.0) for p in target}
    s = sum(raw.values())
    return {p: raw[p] / s for p in raw}


def write_provinces():
    path = HERE / "provinces.csv"
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["province", "pop", "lon", "lat", "region"])
        for row in PROVINCES:
            w.writerow(row)
    print("wrote", path)


def write_votes(year, target, bias, parties):
    path = HERE / f"votes-{year}.csv"
    # 假設總有效票（約數，只求比例；模型只用相對值）
    total_votes = 23_200_000 if year == 2025 else 24_500_000
    pop_sum = sum(p[1] for p in PROVINCES)
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow(["province", "pop", "lon", "lat", "region"] + parties)
        for name, pop, lon, lat, region in PROVINCES:
            sh = shares(target, bias, name)
            n = int(total_votes * pop / pop_sum)
            votes = {p: int(n * sh[p]) for p in parties}
            # 補齊尾差
            votes[parties[0]] += n - sum(votes.values())
            w.writerow([name, pop, lon, lat, region] + [votes[p] for p in parties])
    print("wrote", path)



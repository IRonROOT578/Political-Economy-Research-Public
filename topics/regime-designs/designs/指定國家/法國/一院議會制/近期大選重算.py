def pairwise(fp, a, b, orders):
    return sum(v * w for g, v in fp.items() for w, od in orders[g] if od.index(a) < od.index(b))


def condorcet(fp, finals, orders):
    """Ranked Pairs。回傳 (勝者, 是否循環, 兩兩表)。"""
    pw = {(a, b): pairwise(fp, a, b, orders) for a in finals for b in finals if a != b}
    for a in finals:
        if all(pw[(a, b)] > pw[(b, a)] for b in finals if b != a):
            return a, False, pw
    wins = sorted(((pw[(a, b)], a, b) for a in finals for b in finals
                   if a != b and pw[(a, b)] > pw[(b, a)]), reverse=True)
    locked = set()

    def reaches(x, y):
        seen, todo = set(), [x]
        while todo:
            n = todo.pop()
            if n == y:
                return True
            seen.add(n)
            todo += [b for a, b in locked if a == n and b not in seen]
        return False

    for _, a, b in wins:
        if not reaches(b, a):
            locked.add((a, b))
    beaten = {b for _, b in locked}
    return next(a for a in finals if a not in beaten), True, pw


def region_seats(circs):
    """單一 230 依 2024 選舉人數（不含海外法國人）分到 14 區。"""
    ins = [0] * len(DEPTS)
    where = {d: i for i, ds in enumerate(DEPTS) for d in ds}
    for dep, _, n, _ in circs:
        if dep != DROPPED:
            ins[where[dep]] += n
    got = largest_remainder(dict(enumerate(ins)), 230)
    return [got[i] for i in range(len(DEPTS))]


def merge(circs, seats, shift=False):
    """回傳 [(區號, {群: 票}, 選舉人)]，每區 seats[i] 個新選區。

    shift：把區內開頭約半個新選區的舊選區移到最後再切，所有切點都移動（頭尾兩段合成一區）。"""
    out = []
    for i, ds in enumerate(DEPTS):
        rows = sorted((c for c in circs if c[0] in ds), key=lambda c: (ds.index(c[0]), c[1]))
        target = sum(c[2] for c in rows) / seats[i]
        if shift and seats[i] > 1:
            k, acc = 0, 0
            while acc < target / 2:
                acc += rows[k][2]
                k += 1
            rows = rows[k:] + rows[:k]
        cur, room, ins = {g: 0.0 for g in COLS}, target, 0.0
        for _, _, n, votes in rows:
            left = 1.0
            while left > 1e-12:
                take = min(left, room / n)
                for g, v in zip(COLS, votes):
                    cur[g] += v * take
                ins += n * take
                room -= n * take
                left -= take
                if room <= 1e-6 * target:
                    out.append((i, cur, ins))
                    cur, room, ins = {g: 0.0 for g in COLS}, target, 0.0
        if ins > 1e-6 * target:          # 浮點殘渣併入最後一區
            for g in COLS:
                out[-1][1][g] += cur[g]
        assert sum(1 for o in out if o[0] == i) == seats[i], (i, seats[i])
    return out


def single(districts, orders, rule="condorcet"):
    """回傳 [(區號, 勝者, 是否循環, 第一偏好, 兩兩表)]。rule="runoff"：前 2 名對決（現行兩輪多數決的近似）。"""
    res = []
    for i, fp, _ in districts:
        finals = sorted(BLOCS, key=lambda b: fp[b], reverse=True)
        if rule == "runoff":
            a, b = finals[:2]
            w = a if pairwise(fp, a, b, orders) >= pairwise(fp, b, a, orders) else b
            res.append((i, w, False, fp, None))
            continue
        w, cyc, pw = condorcet(fp, finals[:3], orders)
        res.append((i, w, cyc, fp, pw))
    return res


